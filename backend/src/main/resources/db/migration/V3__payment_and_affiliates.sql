-- Adiciona campos de rastreamento de pagamento externo e afiliação

ALTER TABLE orders ADD COLUMN IF NOT EXISTS external_transaction_id VARCHAR(100);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS affiliate_code VARCHAR(50);
ALTER TABLE orders ADD COLUMN IF NOT EXISTS commission_amount NUMERIC(10, 2) DEFAULT 0.00;

CREATE INDEX IF NOT EXISTS idx_orders_external_tx ON orders(external_transaction_id);
CREATE INDEX IF NOT EXISTS idx_orders_affiliate_code ON orders(affiliate_code);

-- Tabela para gestão e repasse de comissões de afiliados (Personal Trainers / Nutricionistas)
CREATE TABLE IF NOT EXISTS affiliate_commissions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    affiliate_code VARCHAR(50) NOT NULL,
    order_id BIGINT NOT NULL,
    order_number VARCHAR(64) NOT NULL,
    order_total NUMERIC(10, 2) NOT NULL,
    commission_rate NUMERIC(5, 2) NOT NULL,
    commission_amount NUMERIC(10, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    created_at TIMESTAMP NOT NULL,
    paid_at TIMESTAMP,
    CONSTRAINT fk_affiliate_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_affiliate_commissions_code ON affiliate_commissions(affiliate_code);
CREATE INDEX IF NOT EXISTS idx_affiliate_commissions_status ON affiliate_commissions(status);
