-- ==============================================================================
-- FittShop Production Database Schema (Flyway V1 Migration)
-- Compatible with PostgreSQL 15/16 and H2 Database
-- ==============================================================================

-- 1. Table: products
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    description TEXT,
    price NUMERIC(10, 2) NOT NULL,
    category VARCHAR(50) NOT NULL,
    image_url VARCHAR(255),
    nutritional_info TEXT,
    target_goal VARCHAR(50),
    stock_quantity INTEGER NOT NULL DEFAULT 0,
    min_stock_threshold INTEGER NOT NULL DEFAULT 5,
    batch_code VARCHAR(50),
    expiration_date DATE,
    weight_kg DOUBLE PRECISION DEFAULT 0.5,
    version BIGINT DEFAULT 0
);

CREATE INDEX IF NOT EXISTS idx_products_sku ON products(sku);
CREATE INDEX IF NOT EXISTS idx_products_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_products_target_goal ON products(target_goal);

-- 2. Table: customers
CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    password VARCHAR(120) NOT NULL,
    cpf VARCHAR(20),
    phone VARCHAR(20),
    role VARCHAR(30) NOT NULL DEFAULT 'ROLE_CUSTOMER',
    goal VARCHAR(50),
    weight_kg DOUBLE PRECISION,
    height_meters DOUBLE PRECISION,
    weekly_workouts INTEGER,
    experience_level VARCHAR(50)
);

CREATE INDEX IF NOT EXISTS idx_customers_email ON customers(email);

-- 3. Table: orders
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(64) NOT NULL UNIQUE,
    customer_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    freight_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL,
    payment_method VARCHAR(30) NOT NULL,
    reservation_uuid VARCHAR(64),
    tracking_code VARCHAR(64),
    seller_code VARCHAR(50),
    delivery_zip_code VARCHAR(20),
    delivery_address VARCHAR(255),
    fitt_coins_earned INTEGER DEFAULT 0,
    fitt_coins_redeemed INTEGER DEFAULT 0,
    created_at TIMESTAMP NOT NULL,
    paid_at TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_orders_number ON orders(order_number);
CREATE INDEX IF NOT EXISTS idx_orders_status ON orders(status);
CREATE INDEX IF NOT EXISTS idx_orders_customer ON orders(customer_id);

-- 4. Table: order_items
CREATE TABLE IF NOT EXISTS order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    product_name VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    total_price NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_order_items_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_order_items_order ON order_items(order_id);

-- 5. Table: stock_reservations
CREATE TABLE IF NOT EXISTS stock_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_uuid VARCHAR(64) NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL,
    expires_at TIMESTAMP NOT NULL,
    status VARCHAR(30) NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_stock_res_uuid ON stock_reservations(reservation_uuid);
CREATE INDEX IF NOT EXISTS idx_stock_res_product_status ON stock_reservations(product_id, status);

-- 6. Table: loyalty_accounts
CREATE TABLE IF NOT EXISTS loyalty_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL UNIQUE,
    fitt_coins_balance INTEGER NOT NULL DEFAULT 0,
    tier_level VARCHAR(30) NOT NULL DEFAULT 'BRONZE',
    updated_at TIMESTAMP NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_loyalty_customer ON loyalty_accounts(customer_id);
